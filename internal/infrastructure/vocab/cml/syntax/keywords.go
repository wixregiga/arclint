// IsKeyword reports whether name is a reserved CML token spelling. It uses the
// grammar keyword table and the literal terminal table shared with the lexer,
// including punctuation and multiword keywords. Escaped spellings are not keywords.
func IsKeyword(name string) bool {
	g, err := cmlGrammar()
	return err == nil && isKeyword(name, g)
}

func isKeyword(name string, g *grammar) bool {
	if g.keywords[name] {
		return true
	}
	for _, terminal := range literalTerminals {
		for _, spelling := range terminal.forms {
			if name == spelling {
				return true
			}
		}
	}
	return false
}
