//go:embed sdk/types_gen.ts
var sdkTypesTS string

// sdkAPIDecl is the single source of the public SDK function contract.
// go generate writes sdk/api_gen.ts for the TypeScript implementation;
// SDKInit uses this same string for the published editor declarations.
const sdkAPIDecl = `// SDK API contract shared by the runtime source and published editor types.
// Wire types are generated from the Go host; SDKInit embeds them in the same module.
import type {
  FileInfo,
  ImportInfo,
  FactsInfo,
  ViolationInput,
  DomainInfo,
} from "./types_gen";

export type Capability = "exact" | "structural" | "heuristic" | "advisory";

/** Published TermCases: renderings of a recorded vocabulary term as a
 * path or identifier segment. The same closed set rules.arclint.yaml accepts in
 * {name:<case>} placeholders. */
export type TermCase =
  | "flatcase"
  | "snake_case"
  | "kebab-case"
  | "camelCase"
  | "PascalCase";

export interface Ctx {
  /** Repository files, optionally filtered by a doublestar glob. */
  files(glob?: string): FileInfo[];
  /** Read one file's content. Throws on unreadable paths. */
  read(path: string): string;
  /** Classified imports of one file, for every active language target. */
  imports(path: string): ImportInfo[];
  /** Declared zone names to their member file paths. */
  zones(): Record<string, string[]>;
  /** Already-observed declarations, imports, and Zone memberships for one
   * selected subject, including incident dependencies; null outside Scope.
   * Check availability flags before treating empty arrays as observations. */
  facts(path: string): FactsInfo | null;
  /** The sorted zone names a file belongs to. */
  zoneOf(path: string): string[];
  /** The project's recorded domain model, read from the domain file
   * named by domain.file in rules.arclint.yaml, else the first of
   * domain.arclint.yaml, domain.arclint.yml and domain.arclint.cml that
   * exists; empty collections when the project records none. Read-only:
   * declaring knowledge never creates a diagnostic by itself. */
  domain(): DomainInfo;
  /** Render a recorded term in one published TermCase, the host's
   * one casing implementation, identical to what rules.arclint.yaml
   * {name:<case>} placeholders resolve with. Throws on an unknown
   * case and on terms without letters or digits. */
  caseTerm(term: string, termCase: TermCase): string;
  /** Report one violation. */
  report(v: ViolationInput): void;
}

export interface Schema {
  optional(): Schema;
  default(v: unknown): Schema;
  describe(d: string): Schema;
  toJSON(): Record<string, unknown>;
}

/** Minimal zod-style schema builder producing JSON Schema; the host
 * validates rules.arclint.yaml params against it before check() runs. */
export declare const s: {
  string(): Schema;
  number(): Schema;
  integer(): Schema;
  boolean(): Schema;
  enum(...values: string[]): Schema;
  array(items: Schema): Schema;
  object(props: Record<string, Schema>): Schema;
};

export interface RuleDef {
  /** Unique rule type name, referenced by rules.arclint.yaml entries. */
  type: string;
  /** One-line summary shown by arclint rules. */
  description?: string;
  /** How this rule enforces its claim: exact (imports/syntax facts),
   * structural (paths/declarations), heuristic (names/regex/complexity),
   * advisory (guidance only). Default: heuristic, the conservative claim. */
  capability?: Capability;
  /** Params schema; YAML params are host-validated against it. */
  params?: Schema;
  check(ctx: Ctx, params: Record<string, unknown>): void;
}

export declare function defineRule(def: RuleDef): unknown;
`

const sdkTsconfig = `{
  "compilerOptions": {
    "target": "ES2017",
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "strict": true,
    "noEmit": true,
    "paths": {
      "arclint": ["./arclint.d.ts"]
    }
  },
  "include": ["*.ts"]
}
`

// SDKInit writes .arclint/extensions/arclint.d.ts (assembled from the
// tygo-generated host types plus the SDK API declaration) and a
// tsconfig.json, giving authors full editor typing with no npm install.
// It returns the written paths.
func SDKInit(repoRoot string) ([]string, error) {
	dir := filepath.Join(repoRoot, filepath.FromSlash(ExtensionsDir))
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, fmt.Errorf("create %s: %w", dir, err)
	}

	var b strings.Builder
	b.WriteString("// arclint extension SDK type declarations.\n")
	b.WriteString("// Generated by `arclint sdk init`; wire types derive from the Go host\n")
	b.WriteString("// structs (internal/infrastructure/extension/sobek/types.go) via tygo. Regenerate after upgrading.\n")
	b.WriteString("declare module \"arclint\" {\n")
	for _, block := range []string{sdkTypesTS, sdkAPIDecl} {
		inTypeImport := false
		for _, line := range strings.Split(block, "\n") {
			// Both contracts are placed in one ambient module, so their
			// type-only import is unnecessary in the published declaration.
			if inTypeImport || strings.HasPrefix(strings.TrimSpace(line), "import type ") {
				inTypeImport = !strings.Contains(line, ";")
				continue
			}
			if strings.TrimSpace(line) == "" {
				b.WriteString("\n")
				continue
			}
			// The published module is already ambient; its members omit declare.
			line = strings.Replace(line, "export declare ", "export ", 1)
			b.WriteString("  " + line + "\n")
		}
	}
	b.WriteString("}\n")

	dts := filepath.Join(dir, "arclint.d.ts")
	if err := os.WriteFile(dts, []byte(b.String()), 0o600); err != nil {
		return nil, fmt.Errorf("write %s: %w", dts, err)
	}
	tsconfig := filepath.Join(dir, "tsconfig.json")
	if err := os.WriteFile(tsconfig, []byte(sdkTsconfig), 0o600); err != nil {
		return nil, fmt.Errorf("write %s: %w", tsconfig, err)
	}
	return []string{dts, tsconfig}, nil
}

// Describe returns a one-line summary for `arclint rules ls`: the
// author's description when defineRule declares one, else a fallback.
func (rt *RuleType) Describe() string {
	if rt.Description != "" {
		return rt.Description
	}
	return fmt.Sprintf("extension rule type %q from %s", rt.Name, rt.SourcePath)
}
